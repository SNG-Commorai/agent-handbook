import fs from 'node:fs';
import assert from 'node:assert/strict';
import MarkdownIt from 'markdown-it';
const md = new MarkdownIt();
const source = fs.readFileSync('tutorial.md','utf8');
const html = fs.readFileSync('index.html','utf8');
const manifest = JSON.parse(fs.readFileSync('content-manifest.json','utf8'));
const tokens = md.parse(source,{});
const sourceHeadings = tokens.filter(t=>t.type==='heading_open');
assert.equal(manifest.headings.length,sourceHeadings.length,'Heading inventory differs from source');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'Duplicate anchors');
for(const m of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(m[1]),`Broken anchor ${m[1]}`);
for(const m of html.matchAll(/(?:href|src)="\.\/([^"#]+)"/g)) assert(fs.existsSync(m[1]),`Missing local file ${m[1]}`);
const decode=s=>s.replaceAll('&lt;','<').replaceAll('&gt;','>').replaceAll('&quot;','"').replaceAll('&#39;',"'").replaceAll('&amp;','&');
const renderedCode=[...html.matchAll(/<pre><code[^>]*>([\s\S]*?)<\/code><\/pre>/g)].map(m=>decode(m[1]));
const sourceCode=tokens.filter(t=>t.type==='fence').map(t=>t.content);
assert.deepEqual(renderedCode,sourceCode,'Prompt/code text changed during rendering');
assert.equal([...html.matchAll(/<table>/g)].length,tokens.filter(t=>t.type==='table_open').length,'Table missing');
assert(!html.includes('href="https://justmysocks6"'),'Feishu-escaped URL was truncated');
assert(!html.includes('Images_attachments/'),'Unmigrated attachment path');
console.log(`Content checks passed: ${manifest.headings.length} headings, ${sourceCode.length} exact code blocks, local files and all anchors valid.`);
